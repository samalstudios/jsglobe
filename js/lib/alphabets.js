export const letterKey = (letter) => letter.glyph;

// what someone has to answer, and what else could plausibly be offered instead
export const choicesFor = (letters, answer, count = 4) => {
  const others = letters.filter((letter) => letter.latin !== answer.latin);
  const picked = [];
  while (picked.length < Math.min(count - 1, others.length)) {
    const at = Math.floor(Math.random() * others.length);
    const [taken] = others.splice(at, 1);
    if (!picked.some((letter) => letter.latin === taken.latin)) picked.push(taken);
  }
  const all = [answer, ...picked];
  for (let at = all.length - 1; at > 0; at -= 1) {
    const swap = Math.floor(Math.random() * (at + 1));
    [all[at], all[swap]] = [all[swap], all[at]];
  }
  return all;
};

export const LEARNED_AT = 4;

export const strengthOf = (record) => {
  if (!record?.seen) return 0;
  return Math.max(0, Math.min(1, (record.streak ?? 0) / LEARNED_AT));
};

// the ones gone wrong most recently come round again soonest, and anything
// never seen comes before anything already answered
export const nextLetter = (letters, progress, avoid) => {
  const weigh = (letter) => {
    const record = progress[letterKey(letter)];
    if (!record?.seen) return 100;
    const wrong = (record.wrong ?? 0) + 1;
    const streak = Math.min(record.streak ?? 0, LEARNED_AT);
    return Math.max(1, (wrong * 12) / (streak + 1));
  };

  const pool = letters.filter((letter) => letters.length < 2 || letterKey(letter) !== avoid);
  const total = pool.reduce((sum, letter) => sum + weigh(letter), 0);
  let ticket = Math.random() * total;
  for (const letter of pool) {
    ticket -= weigh(letter);
    if (ticket <= 0) return letter;
  }
  return pool[pool.length - 1];
};

export const scoreOf = (letters, progress) => {
  let learned = 0;
  let started = 0;
  for (const letter of letters) {
    const record = progress[letterKey(letter)];
    if (!record?.seen) continue;
    started += 1;
    if ((record.streak ?? 0) >= LEARNED_AT) learned += 1;
  }
  return { learned, started, total: letters.length };
};
