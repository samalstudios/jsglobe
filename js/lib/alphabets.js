const VOWEL_CUES = {
  a: 'a in father',
  i: 'ee in see',
  u: 'oo in boot, with the lips barely rounded',
  e: 'e in bed',
  o: 'o in more',
};

const ODD_KANA = {
  shi: 'she',
  chi: 'chee',
  tsu: 'ts in cats, then oo',
  fu: 'between f and h, blown softly',
  n: 'n on its own, the only letter that is not a syllable',
  wo: 'said o, used only to mark the object of a sentence',
};

const kanaSound = (latin) => {
  if (ODD_KANA[latin]) return ODD_KANA[latin];
  const vowel = latin.slice(-1);
  const cue = VOWEL_CUES[vowel];
  if (!cue) return latin;
  const head = latin.slice(0, -1);
  return head ? `${head} then ${cue}` : cue;
};

const kana = (rows) =>
  rows.flatMap(([glyphs, latins]) =>
    [...glyphs].map((glyph, at) => ({
      glyph,
      name: latins[at],
      latin: latins[at],
      sound: kanaSound(latins[at]),
    })),
  );

